def portfolio_log_returns(weights):
    """Месечен log-принос на портфолио со дадени пондери.
    Пондерите важат за обични (simple) приноси, па прво конвертираме
    log -> simple, ги множиме со пондерите, и враќаме назад во log."""
    simple_returns = np.exp(df[stocks]) - 1
    portfolio_simple = simple_returns.dot(weights)
    return np.log1p(portfolio_simple)      # log1p(x) = log(1 + x)


def drawdown(log_returns):
    """Drawdown = колку сме под последниот врв на вредноста на портфолиото.
    Работи и за една колона (Series) и за повеќе колони (DataFrame)."""
    wealth = np.exp(log_returns.cumsum())  # вредност на портфолио (почнува од 1)
    peak = wealth.cummax()                 # највисока вредност досега
    return wealth / peak - 1               # 0 = на врв, -0.2 = 20% под врвот


def objective(ponderi, prinosi, cov_matrix):     # (weights, returns, cov_matrix)
    """Целна функција: принос/ризик (со минус, бидејќи minimize бара минимум)."""
    portfolio_return = ponderi @ prinosi
    portfolio_volatility = np.sqrt(ponderi @ cov_matrix @ ponderi)
    return -(portfolio_return / portfolio_volatility)


def plot_portfolios(data, title, ylabel, filename):
    """Црта линија за секое портфолио и го зачувува графикот во images/."""
    plt.figure(figsize=(10, 5))
