# ============================================================
# 9. БЕТА: HUBER НАСПРАМУ OLS
#    (README: Huber M-estimator vs OLS)
# ============================================================

huber_logic = sm.robust.norms.HuberT(t=1.345)
X_const = sm.add_constant(df['MBI_10'])

# Бета за секоја акција и за двете портфолија
beta_inputs = pd.concat([df[stocks], portfolios[['SLSQP', 'Equal']]], axis=1)

beta_rows = {}
for name in beta_inputs.columns:
    ols_fit = sm.OLS(beta_inputs[name], X_const).fit()
    huber_fit = sm.RLM(beta_inputs[name], X_const, M=huber_logic).fit()
    beta_rows[name] = {'Beta_OLS': ols_fit.params['MBI_10'],
                       'Beta_Huber': huber_fit.params['MBI_10']}

tabela_beta = pd.DataFrame(beta_rows).T
tabela_beta['Difference'] = tabela_beta['Beta_Huber'] - tabela_beta['Beta_OLS']
print("\n=== ТАБЕЛА 4: Бета (OLS наспроти Huber) ===")
