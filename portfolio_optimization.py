# 4. SLSQP ОПТИМИЗАЦИЈА
#    (README: Constrained SLSQP, табела со пондери)
# ============================================================

mean_returns_array = df[stocks].mean().values    # облик (5,)
cov_matrix = df[stocks].cov().values             # облик (5, 5)

number_of_stocks = len(stocks)
equal_weights = np.array([1. / number_of_stocks] * number_of_stocks)   # секоја акција 1/5
stock_weight_constraints = ({'type': 'eq', 'fun': lambda x: np.sum(x) - 1})   # збир = 1
stock_weight_boundary = tuple((0, 0.45) for asset in range(number_of_stocks))  # 0% до 45%

result_optimization_weights = minimize(fun=objective,
                                       x0=equal_weights,
                                       args=(mean_returns_array, cov_matrix),
                                       method='SLSQP',
                                       bounds=stock_weight_boundary,
                                       constraints=stock_weight_constraints)

print("\nОптимизација успешна:", result_optimization_weights.success)
slsqp_optimized_weights = result_optimization_weights.x

# Табела: SLSQP пондери наспроти еднакви пондери
tabela_ponderi = pd.DataFrame({
    'SLSQP_weights_%': slsqp_optimized_weights * 100,
    'Equal_weights_%': equal_weights * 100
}, index=stocks)
print("\n=== Пондери ===")
print(tabela_ponderi.round(2))


